#!/usr/bin/env python3
"""Summarize benchmark runs under docs/results into docs/results/README.md.

    uv run --project API python scripts/summarize_results.py --results docs/results

One table per (model, prompt): rows are methods; columns are plus pass@1 mean
across seeds with min-max, base pass@1 mean, the paired bootstrap 95% CI of
the difference from ``original`` (same seed, same tasks; 2,000 resamples over
the test tasks, seeds pooled), and wall-clock. Numbers read ``45.5% (90/198)``.
"""

from __future__ import annotations

import argparse
import json
import random
import statistics
from collections import defaultdict
from pathlib import Path
from typing import Any

REPO_ROOT = Path(__file__).resolve().parent.parent
METHOD_ORDER = [
    "original",
    "one_line",
    "random_demos",
    "coverage_demos",
    "gepa",
    "gepa_demos",
]
RESAMPLES = 2000


def load_results(results_dir: Path) -> list[dict[str, Any]]:
    runs = []
    for path in sorted(results_dir.glob("*/*/*/seed*.json")):
        data = json.loads(path.read_text())
        data["_path"] = path
        runs.append(data)
    return runs


def paired_bootstrap_ci(
    diffs: list[float], resamples: int = RESAMPLES, seed: int = 0
) -> tuple[float, float]:
    """95% CI of the mean of paired per-task differences, in percentage points."""
    if not diffs:
        return (0.0, 0.0)
    rng = random.Random(seed)
    n = len(diffs)
    means = []
    for _ in range(resamples):
        total = 0.0
        for _ in range(n):
            total += diffs[rng.randrange(n)]
        means.append(total / n * 100)
    means.sort()
    lo = means[int(0.025 * (resamples - 1))]
    hi = means[int(0.975 * (resamples - 1))]
    return (round(lo, 1), round(hi, 1))


def pct(count: float, n: int) -> str:
    return f"{count / n * 100:.1f}% ({count:g}/{n})" if n else "n/a"


def summarize(runs: list[dict[str, Any]]) -> tuple[str, dict[str, Any]]:
    groups: dict[tuple[str, str], list[dict[str, Any]]] = defaultdict(list)
    for run in runs:
        cfg = run["config"]
        groups[(cfg["model"]["tag"], cfg["prompt_name"])].append(run)

    lines = ["# Benchmark results", ""]
    lines.append(
        "Generated by `scripts/summarize_results.py` from `docs/results/**`. "
        "Scores are pass@1 on the fixed 198-task MBPP+ test split; *plus* means "
        "every assert (EvalPlus's extended inputs included) passed, *base* means "
        "the original MBPP asserts passed. The CI is a paired bootstrap over test "
        f"tasks ({RESAMPLES} resamples, seeds pooled) of the plus difference from "
        "`original` at the same seed."
    )
    lines.append("")
    facts: dict[str, Any] = {}
    for (model, prompt_name), group in sorted(groups.items()):
        prompt_text = group[0]["config"]["prompt"]
        digest = group[0]["config"]["model"]["digest"][:12]
        reflection = group[0]["config"]["reflection_model"]["tag"]
        commit = group[0]["config"]["git_commit"][:9]
        lines.append(f"## {model} · prompt `{prompt_name}`")
        lines.append("")
        lines.append(
            f"Prompt: *{prompt_text}*  \nModel digest `{digest}`, reflection model "
            f"`{reflection}`, commit `{commit}`, budget {group[0]['config']['budget']}, "
            f"{group[0]['config']['demos']} demos."
        )
        lines.append("")
        lines.append(
            "| Method | Seeds | Plus pass@1 mean (min–max) | Base pass@1 mean | "
            "Δ plus vs original, 95% CI | Val plus | Wall-clock |"
        )
        lines.append("|---|---|---|---|---|---|---|")

        by_method: dict[str, dict[int, dict[str, Any]]] = defaultdict(dict)
        for run in group:
            by_method[run["config"]["method"]][run["config"]["seed"]] = run
        originals = by_method.get("original", {})
        n = next(iter(group))["test"]["n"]
        methods = [m for m in METHOD_ORDER if m in by_method] + sorted(
            m for m in by_method if m not in METHOD_ORDER
        )
        for method in methods:
            seeds = sorted(by_method[method])
            plus = [by_method[method][s]["test"]["plus_pass"] for s in seeds]
            base = [by_method[method][s]["test"]["base_pass"] for s in seeds]
            val = [by_method[method][s]["val"]["plus_pass_at_1"] for s in seeds]
            secs = [by_method[method][s]["wall_clock"]["total_seconds"] for s in seeds]
            plus_mean = statistics.mean(plus)
            base_mean = statistics.mean(base)
            plus_cell = pct(plus_mean, n)
            if len(plus) > 1:
                plus_cell += f", {min(plus) / n * 100:.1f}–{max(plus) / n * 100:.1f}"
            diffs: list[float] = []
            for s in seeds:
                base_run = originals.get(s) or (
                    originals.get(min(originals)) if originals else None
                )
                if base_run is None or method == "original":
                    continue
                theirs = {r["task_id"]: r["plus_pass"] for r in base_run["test_rows"]}
                for row in by_method[method][s]["test_rows"]:
                    diffs.append(
                        float(row["plus_pass"]) - float(theirs.get(row["task_id"], 0))
                    )
            if diffs:
                lo, hi = paired_bootstrap_ci(diffs)
                delta = statistics.mean(diffs) * 100
                ci_cell = f"{delta:+.1f} pp [{lo:+.1f}, {hi:+.1f}]"
                facts[f"{model}/{prompt_name}/{method}"] = {
                    "delta": round(delta, 1),
                    "ci": (lo, hi),
                    "plus": plus,
                    "base": base,
                }
            else:
                ci_cell = "—"
            lines.append(
                f"| {method} | {', '.join(map(str, seeds))} | {plus_cell} | {pct(base_mean, n)} | "
                f"{ci_cell} | {statistics.mean(val):.1f}% | {statistics.mean(secs) / 60:.0f} min |"
            )
        lines.append("")
    return "\n".join(lines), facts


def main(argv: list[str] | None = None) -> None:
    parser = argparse.ArgumentParser(
        description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter
    )
    parser.add_argument("--results", type=Path, default=REPO_ROOT / "docs" / "results")
    parser.add_argument(
        "--findings", type=Path, default=None, help="markdown appended under the tables"
    )
    args = parser.parse_args(argv)

    runs = load_results(args.results)
    if not runs:
        raise SystemExit(f"no seed*.json files under {args.results}")
    text, _ = summarize(runs)
    if args.findings and args.findings.exists():
        text += "\n" + args.findings.read_text().strip() + "\n"
    out = args.results / "README.md"
    out.write_text(text)
    print(f"wrote {out} from {len(runs)} runs")
    print(text)


if __name__ == "__main__":
    main()
